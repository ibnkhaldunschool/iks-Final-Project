const banglaToEnglishDigits = (str) => {
  const banglaDigits = { '০': 0, '১': 1, '২': 2, '৩': 3, '৪': 4, '৫': 5, '৬': 6, '৭': 7, '৮': 8, '৯': 9 };
  return str.replace(/[০-৯]/g, match => banglaDigits[match]);
};

const monthMap = {
  'জানুয়ারী': 0, 'জানুয়ারি': 0, 'ফেব্রুয়ারী': 1, 'ফেব্রুয়ারি': 1,
  'মার্চ': 2, 'এপ্রিল': 3, 'মে': 4, 'জুন': 5,
  'জুলাই': 6, 'আগস্ট': 7, 'সেপ্টেম্বর': 8,
  'অক্টোবর': 9, 'নভেম্বর': 10, 'ডিসেম্বর': 11
};

window.NOTICES.sort((a, b) => {
  let dayA = parseInt(banglaToEnglishDigits(a.date.d));
  let monthA = monthMap[a.date.m.trim()];
  let yearA = parseInt(banglaToEnglishDigits(a.date.y));
  let dateA = new Date(yearA, monthA, dayA).getTime();

  let dayB = parseInt(banglaToEnglishDigits(b.date.d));
  let monthB = monthMap[b.date.m.trim()];
  let yearB = parseInt(banglaToEnglishDigits(b.date.y));
  let dateB = new Date(yearB, monthB, dayB).getTime();

  return dateB - dateA;
});
